if uploaded_file is not None:
    # Display the uploaded image to the user
    image = Image.open(uploaded_file)
    st.image(image, caption="Your Uploaded Image", width=200)

    # 4. Process the image to match the training data
    with st.spinner("Processing image and predicting..."):
        # Convert to grayscale
        img_gray = image.convert('L')

        # Invert colors (MNIST needs white text on a black background)
        img_inverted = ImageOps.invert(img_gray)

        # Resize to exactly 28x28 pixels
        img_resized = img_inverted.resize((28, 28))

        # Format into a normalized NumPy array (0.0 to 1.0)
        img_array = np.array(img_resized) / 255.0

        # Reshape to (1, 28, 28) to match the model's batch expectation
        img_array = np.expand_dims(img_array, axis=0)

        # 5. Make the Prediction
        prediction = model.predict(img_array)
        predicted_digit = np.argmax(prediction)
        confidence = np.max(prediction) * 100

        # 6. Display Results beautifully
        st.success(f"### 🔮 Prediction: This is a **{predicted_digit}**")
        st.metric(label="Model Confidence", value=f"{confidence:.2f}%")
