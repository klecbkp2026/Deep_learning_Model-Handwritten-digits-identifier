import tensorflow as tf
from tensorflow.keras import layers, models
import numpy as np
import matplotlib.pyplot as plt

# 1. LOAD AND SPLIT THE MNIST DATASET
(X_train, y_train), (X_test, y_test) = tf.keras.datasets.mnist.load_data()

# 2. PREPROCESS THE DATA
# Scale pixel values from 0-255 to 0-1
X_train = X_train / 255.0
X_test = X_test / 255.0

# 3. BUILD THE NEURAL NETWORK ARCHITECTURE
model = models.Sequential([
    # Flatten the 28x28 image matrices into a 1D array of 784 pixels
    layers.Flatten(input_shape=(28, 28)),

    # Hidden layer with 128 neurons to detect shapes/edges
    layers.Dense(128, activation='relu'),

    # Output layer with 10 neurons (one for each digit 0-9)
    layers.Dense(10, activation='softmax')
])

# 4. COMPILE THE MODEL
model.compile(
    optimizer='adam',
    loss='sparse_categorical_crossentropy',
    metrics=['accuracy']
)

# 5. TRAIN THE MODEL
print("--- Training Started ---")
model.fit(X_train, y_train, epochs=5, batch_size=32)

# 6. EVALUATE THE MODEL ON UNSEEN TEST DATA
print("\n--- Evaluation on Test Data ---")
test_loss, test_acc = model.evaluate(X_test, y_test)
print(f"Test Accuracy: {test_acc * 100:.2f}%")

# 7. MAKE A PREDICTION
# Grab the very first image from the test set
sample_image = X_test[0]
true_label = y_test[0]

# Reshape the image because the model expects a batch of images
prediction = model.predict(np.expand_dims(sample_image, axis=0))
predicted_digit = np.argmax(prediction)

# Display the result
print(f"\nPredicted Digit: {predicted_digit} (True Label: {true_label})")

# Save the trained model
model.save('digit_model.h5')

